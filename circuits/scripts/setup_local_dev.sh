#!/bin/bash
# Local-dev Powers of Tau + Groth16 setup for generic_verifier.
# Use only when audited ptau mirrors are unavailable. NOT FOR PRODUCTION.
set -euo pipefail
cd "$(dirname "$0")/.."
CIRCUIT_NAME="${1:-generic_verifier}"
BUILD_DIR="./build"
MOPRO_ASSETS="../mopro/assets"
MOBILE_ASSETS="../mobile/assets"
mkdir -p "$BUILD_DIR" "$MOPRO_ASSETS" "$MOBILE_ASSETS"

echo "=== Compile circuit ==="
circom "src/${CIRCUIT_NAME}.circom" --r1cs --wasm --sym -o "$BUILD_DIR"

if [ ! -f "$BUILD_DIR/pot12_final.ptau" ]; then
  echo "=== Local Powers of Tau (2^12, DEV ONLY) ==="
  npx snarkjs powersoftau new bn128 12 "$BUILD_DIR/pot12_0000.ptau" -v
  echo "zk-MatchID local-dev contributor $(date -Iseconds)" | \
    npx snarkjs powersoftau contribute "$BUILD_DIR/pot12_0000.ptau" "$BUILD_DIR/pot12_0001.ptau" \
      --name="zk-MatchID local-dev contributor" -v
  BEACON=a1b2c3d4e5f60718293a4b5c6d7e8f90112233445566778899aabbccddeeff00
  npx snarkjs powersoftau beacon "$BUILD_DIR/pot12_0001.ptau" "$BUILD_DIR/pot12_beacon.ptau" "$BEACON" 10 \
    -n="zk-MatchID local-dev beacon"
  npx snarkjs powersoftau prepare phase2 "$BUILD_DIR/pot12_beacon.ptau" "$BUILD_DIR/pot12_final.ptau" -v
  cat > "$BUILD_DIR/DEV_CEREMONY_README.txt" <<'NOTE'
DEV CEREMONY ONLY — NOT FOR PRODUCTION. Generated by setup_local_dev.sh
because public Hermez/PSE ptau mirrors were unreachable. Re-run against an
audited powersOfTau28_hez_final_12.ptau before any production use.
NOTE
fi

PTAU="$BUILD_DIR/pot12_final.ptau"
if [ -f "$BUILD_DIR/powersOfTau28_hez_final_12.ptau" ]; then
  PTAU="$BUILD_DIR/powersOfTau28_hez_final_12.ptau"
  echo "Using audited-style ptau: $PTAU"
fi

echo "=== Groth16 setup ==="
npx snarkjs groth16 setup "$BUILD_DIR/${CIRCUIT_NAME}.r1cs" "$PTAU" "$BUILD_DIR/${CIRCUIT_NAME}_0000.zkey"
echo "zk-MatchID Phase 2 $(date -Iseconds)" | \
  npx snarkjs zkey contribute "$BUILD_DIR/${CIRCUIT_NAME}_0000.zkey" \
    "$BUILD_DIR/${CIRCUIT_NAME}_final.zkey" --name="zk-MatchID Contributor" -v
npx snarkjs zkey export verificationkey "$BUILD_DIR/${CIRCUIT_NAME}_final.zkey" "$BUILD_DIR/verification_key.json"
npx snarkjs zkey export solidityverifier "$BUILD_DIR/${CIRCUIT_NAME}_final.zkey" \
  "../contracts/contracts/Groth16Verifier.sol"

cp "$BUILD_DIR/${CIRCUIT_NAME}_final.zkey" "$MOPRO_ASSETS/"
cp "$BUILD_DIR/${CIRCUIT_NAME}.r1cs" "$MOPRO_ASSETS/"
cp "$BUILD_DIR/${CIRCUIT_NAME}_js/${CIRCUIT_NAME}.wasm" "$MOPRO_ASSETS/${CIRCUIT_NAME}.wasm"
cp "$BUILD_DIR/verification_key.json" "$MOPRO_ASSETS/"
cp "$BUILD_DIR/verification_key.json" "$MOBILE_ASSETS/"
cp "$BUILD_DIR/DEV_CEREMONY_README.txt" "$MOPRO_ASSETS/" 2>/dev/null || true
echo "Done. wasm/zkey/vkey synchronized under mopro/assets and mobile/assets."
